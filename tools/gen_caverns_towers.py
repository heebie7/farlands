#!/usr/bin/env python3
"""
Generates the trial-chamber towers that stand in a caverns zone.

What Т asked for, in order:

  2026-08-31: "не колонны, а более абстрактные, очень высокие формы из этих трайлчемберов...
  просто друг на друге будет стоять много хаотично сгенерированных трайл-чемберов".

  2026-11-12, on v0.10.0: "до сих пор это просто несколько комнат, летающих рядом. Стоит их
  сделать примерно в три раза больше комнат. Сделать это полноценными башнями, а то это просто
  несоединённые комнаты... чтобы они поднимались до максимальной высоты в мире. С самого низа до
  вышины и куда плотнее."

How that turns into data, since v0.11.0:

  * ONE structure, type farlands:tower (TowerStructure.java), and ONE structure set. The tower is
    built in Java: columns of rooms, each room generated by vanilla's own jigsaw code and then
    moved so that it sits wall to wall with its neighbours and directly on the room below, from
    the bottom of the world to the build limit. A 2x2 tower is ~100 rooms.

    v0.8-v0.10 had one vanilla jigsaw structure PER TIER, thirty structure sets sharing a salt.
    That could not make a tower: a jigsaw start piece is rotated at random around the corner of
    its chunk, so every tier landed in a different quadrant, and nothing knew how big the room
    it rolled was. Do not go back to it.

  * Real trial chambers, real spawners, real vaults, real loot - Т said leave them. The pool is
    minecraft:trial_chambers/chambers/end, the pool of actual chambers, NOT vanilla's own start
    pool minecraft:trial_chambers/chamber/end, which is only corridor end caps.

  * pool_aliases and spawn_overrides are copied verbatim from vanilla's trial_chambers.json.
    They are not decoration: the chamber pools reference alias pools like
    minecraft:trial_chambers/spawner/contents/melee that DO NOT EXIST as files. Drop the aliases
    and the jigsaw asks for a template pool that is not there.

  * terrain_adaptation "none", because Т ruled out encapsulate: bare rooms in the open, no stone
    column around them.

  * The placement is farlands:zone_spread: random_spread, gated to caverns zones AND to
    dimensions whose terrain has zones at all (see ZoneDimension.java - before v0.11.0 the
    towers also stood in the ordinary overworld).

Run after changing anything here:
    python3 tools/gen_caverns_towers.py
"""

import json
import os
import urllib.request

MCMETA = "https://raw.githubusercontent.com/misode/mcmeta/1.21.11-data/data/minecraft/worldgen/{}.json"
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "src/main/resources/data/farlands/worldgen")
CACHE = os.path.join(os.path.dirname(os.path.abspath(__file__)), ".cache")

# ---------------------------------------------------------------- KNOBS
CAVERNS_ZONE_TYPE = 2      # index of "caverns" in ZoneGridDensityFunction.TYPE_NAMES

# ⚠ SPACING / SEPARATION / SALT must match the TOWER_* constants in ZoneSpreadPlacement.java,
# which is what /farlands towers predicts from.
SPACING = 12               # chunks between towers (~192 blocks)
SEPARATION = 3
SALT = 8412577

POOL = "minecraft:trial_chambers/chambers/end"
SIZE = 5                   # jigsaw depth. Gets the chamber, its slices, its spawners and loot.
MAX_DISTANCE = 112         # room for the chamber to build its own slices (vanilla uses 116)

# Shape of one tower. Rooms in the pool are 24-34 wide, 29 deep and 14 or 19 tall.
COLUMNS_X = 3              # footprint in rooms. 3x2 -> ~150 rooms per tower, ~80x55 blocks (Т 12.11: "в 5 или 6 раз").
COLUMNS_Z = 2              #   2x2 is ~100 rooms (v0.11.0); 1x1 is a single ~25-room shaft.
COLUMN_PITCH = 24          # blocks between column centres. Less than a room is wide on purpose:
                           #   neighbours bite into each other instead of leaving a gap.
OVERLAP = 1                # blocks a room sinks into the one below: its floor IS that ceiling
DRIFT = 2                  # each room steps up to this far sideways from the one below...
MAX_DRIFT = 4              # ...but never further than this from its column. Lean, not scatter.

OLD_TIERS = 30             # v0.8-v0.10 wrote caverns_tower_0..29; removed on every run


def fetch(path):
    os.makedirs(CACHE, exist_ok=True)
    cached = os.path.join(CACHE, path.replace("/", "_") + ".json")
    if not os.path.exists(cached):
        print("downloading vanilla", path)
        urllib.request.urlretrieve(MCMETA.format(path), cached)
    with open(cached) as f:
        return json.load(f)


def write(data, subdir, name):
    directory = os.path.join(DATA, subdir)
    os.makedirs(directory, exist_ok=True)
    with open(os.path.join(directory, name + ".json"), "w") as f:
        json.dump(data, f, indent=2)
        f.write("\n")


def main():
    vanilla = fetch("structure/trial_chambers")

    for tier in range(OLD_TIERS):
        for subdir in ("structure", "structure_set"):
            stale = os.path.join(DATA, subdir, "caverns_tower_%d.json" % tier)
            if os.path.exists(stale):
                os.remove(stale)

    structure = {
        "type": "farlands:tower",
        "biomes": "#minecraft:is_overworld",
        "step": "underground_structures",
        "terrain_adaptation": "none",
        "start_pool": POOL,
        "size": SIZE,
        "max_distance_from_center": MAX_DISTANCE,
        "columns_x": COLUMNS_X,
        "columns_z": COLUMNS_Z,
        "column_pitch": COLUMN_PITCH,
        "overlap": OVERLAP,
        "drift": DRIFT,
        "max_drift": MAX_DRIFT,
        "pool_aliases": vanilla["pool_aliases"],
        "spawn_overrides": vanilla["spawn_overrides"],
    }
    write(structure, "structure", "caverns_tower")

    write(
        {
            "placement": {
                "type": "farlands:zone_spread",
                "spacing": SPACING,
                "separation": SEPARATION,
                "salt": SALT,
                "zone_type": CAVERNS_ZONE_TYPE,
            },
            "structures": [{"structure": "farlands:caverns_tower", "weight": 1}],
        },
        "structure_set",
        "caverns_tower",
    )

    rooms = COLUMNS_X * COLUMNS_Z * round(384 / (16.5 - OVERLAP))
    print("wrote farlands:caverns_tower: %dx%d columns, ~%d rooms, one per ~%d blocks"
          % (COLUMNS_X, COLUMNS_Z, rooms, SPACING * 16))


if __name__ == "__main__":
    main()
