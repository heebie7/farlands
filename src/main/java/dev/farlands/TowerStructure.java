package dev.farlands;

import com.mojang.serialization.Codec;
import com.mojang.serialization.MapCodec;
import com.mojang.serialization.codecs.RecordCodecBuilder;
import net.minecraft.registry.entry.RegistryEntry;
import net.minecraft.structure.StructureLiquidSettings;
import net.minecraft.structure.StructurePiece;
import net.minecraft.structure.StructurePiecesCollector;
import net.minecraft.structure.StructureStart;
import net.minecraft.structure.pool.StructurePool;
import net.minecraft.structure.pool.StructurePoolBasedGenerator;
import net.minecraft.structure.pool.alias.StructurePoolAliasBinding;
import net.minecraft.structure.pool.alias.StructurePoolAliasLookup;
import net.minecraft.util.math.BlockBox;
import net.minecraft.util.math.BlockPos;
import net.minecraft.util.math.ChunkPos;
import net.minecraft.util.math.random.Random;
import net.minecraft.world.HeightLimitView;
import net.minecraft.world.gen.structure.DimensionPadding;
import net.minecraft.world.gen.structure.JigsawStructure;
import net.minecraft.world.gen.structure.Structure;
import net.minecraft.world.gen.structure.StructureType;

import java.util.List;
import java.util.Optional;

/**
 * One whole caverns tower: columns of real trial chambers stacked room on room, wall to wall,
 * from the bottom of the world to the build limit.
 *
 * Why this replaced the v0.8-v0.10 scheme (one vanilla jigsaw structure per tier, 30 structure
 * sets landing on the same chunk): a jigsaw start piece is rotated at random around the CORNER of
 * its start chunk, so every tier landed in one of four quadrants, the tiers were additionally
 * shifted a chunk sideways, and nothing knew how big the room it rolled was. The result was what
 * Т reported on v0.10.0: "просто несколько комнат, летающих рядом... несоединённые комнаты".
 * Thirty rooms scattered through a 90x90x300 volume fill about a seventh of it.
 *
 * Here every room is still generated by vanilla's own jigsaw code - same pool, same spawners,
 * same vaults, same loot, which Т asked to keep - but each finished room is then MOVED, as a
 * whole, to where the tower needs it:
 *
 *   - the footprint is a grid of columns (2x2 by default), `column_pitch` blocks apart, which is
 *     a little less than a room is wide, so neighbouring rooms share walls instead of leaving a
 *     gap;
 *   - each column is stacked from its real bounding boxes: the next room starts where the last
 *     one ended minus `overlap`, so 14-block rooms and 19-block rooms pack without holes and
 *     without anybody guessing a tier step;
 *   - each room drifts a few blocks sideways from the one below (`drift`, capped at `max_drift`),
 *     so the tower leans and bulges instead of being four ruler-straight shafts;
 *   - the last room of a column is pushed down into the one under it so its top sits exactly on
 *     the build limit. Bottom of the world to the top of the world, every tower.
 *
 * A 2x2 tower comes out at roughly 100 rooms against the old 20-30.
 *
 * Moving is done on the finished piece list, not by predicting the rotation: the first piece
 * vanilla returns is the room itself, its bounding box says where it actually ended up, and
 * everything that grew out of it (spawners, vaults, dispensers, addons) is translated by the same
 * amount.
 */
public class TowerStructure extends Structure {
	public static final MapCodec<TowerStructure> CODEC = RecordCodecBuilder.mapCodec(instance -> instance.group(
			configCodecBuilder(instance),
			StructurePool.REGISTRY_CODEC.fieldOf("start_pool").forGetter(s -> s.startPool),
			Codec.intRange(0, 20).fieldOf("size").forGetter(s -> s.size),
			JigsawStructure.MaxDistanceFromCenter.CODEC.fieldOf("max_distance_from_center").forGetter(s -> s.maxDistanceFromCenter),
			Codec.list(StructurePoolAliasBinding.CODEC).optionalFieldOf("pool_aliases", List.of()).forGetter(s -> s.poolAliasBindings),
			Codec.intRange(1, 4).optionalFieldOf("columns_x", 2).forGetter(s -> s.columnsX),
			Codec.intRange(1, 4).optionalFieldOf("columns_z", 2).forGetter(s -> s.columnsZ),
			Codec.intRange(8, 64).optionalFieldOf("column_pitch", 24).forGetter(s -> s.columnPitch),
			Codec.intRange(0, 8).optionalFieldOf("overlap", 1).forGetter(s -> s.overlap),
			Codec.intRange(0, 16).optionalFieldOf("drift", 2).forGetter(s -> s.drift),
			Codec.intRange(0, 32).optionalFieldOf("max_drift", 4).forGetter(s -> s.maxDrift),
			Codec.intRange(1, 64).optionalFieldOf("max_rooms_per_column", 40).forGetter(s -> s.maxRoomsPerColumn)
	).apply(instance, TowerStructure::new));

	public static final StructureType<TowerStructure> TYPE = () -> CODEC;

	/** Rooms are built here first and moved afterwards; mid-world, so nothing clips the limits. */
	private static final int SCRATCH_Y = 96;

	private final RegistryEntry<StructurePool> startPool;
	private final int size;
	private final JigsawStructure.MaxDistanceFromCenter maxDistanceFromCenter;
	private final List<StructurePoolAliasBinding> poolAliasBindings;
	private final int columnsX;
	private final int columnsZ;
	private final int columnPitch;
	private final int overlap;
	private final int drift;
	private final int maxDrift;
	private final int maxRoomsPerColumn;

	public TowerStructure(Structure.Config config, RegistryEntry<StructurePool> startPool, int size,
	                      JigsawStructure.MaxDistanceFromCenter maxDistanceFromCenter,
	                      List<StructurePoolAliasBinding> poolAliasBindings,
	                      int columnsX, int columnsZ, int columnPitch, int overlap,
	                      int drift, int maxDrift, int maxRoomsPerColumn) {
		super(config);
		this.startPool = startPool;
		this.size = size;
		this.maxDistanceFromCenter = maxDistanceFromCenter;
		this.poolAliasBindings = poolAliasBindings;
		this.columnsX = columnsX;
		this.columnsZ = columnsZ;
		this.columnPitch = columnPitch;
		this.overlap = overlap;
		this.drift = drift;
		this.maxDrift = maxDrift;
		this.maxRoomsPerColumn = maxRoomsPerColumn;
	}

	@Override
	protected Optional<Structure.StructurePosition> getStructurePosition(Structure.Context context) {
		ChunkPos chunkPos = context.chunkPos();
		BlockPos centre = new BlockPos(chunkPos.getStartX() + 8, SCRATCH_Y, chunkPos.getStartZ() + 8);
		return Optional.of(new Structure.StructurePosition(centre, collector -> build(context, centre, collector)));
	}

	private void build(Structure.Context context, BlockPos centre, StructurePiecesCollector collector) {
		HeightLimitView world = context.world();
		int bottomY = world.getBottomY();
		int topY = bottomY + world.getHeight() - 1;   // highest block that exists
		Random random = context.random();

		for (int cx = 0; cx < columnsX; cx++) {
			for (int cz = 0; cz < columnsZ; cz++) {
				// Column centres, symmetric around the tower centre.
				int columnX = centre.getX() + (int) Math.round((cx - (columnsX - 1) / 2.0) * columnPitch);
				int columnZ = centre.getZ() + (int) Math.round((cz - (columnsZ - 1) / 2.0) * columnPitch);
				buildColumn(context, centre, collector, random, columnX, columnZ, bottomY, topY);
			}
		}
	}

	private void buildColumn(Structure.Context context, BlockPos scratch, StructurePiecesCollector collector,
	                         Random random, int columnX, int columnZ, int bottomY, int topY) {
		int y = bottomY;
		int offsetX = 0;
		int offsetZ = 0;

		for (int room = 0; room < maxRoomsPerColumn && y <= topY; room++) {
			List<StructurePiece> pieces = generateRoom(context, scratch);
			if (pieces.isEmpty()) {
				return;
			}
			BlockBox box = pieces.get(0).getBoundingBox();
			int height = box.getBlockCountY();
			if (height > topY - bottomY + 1) {
				return;
			}

			// Last room of the column: sink it into the one below so the tower ends flush with
			// the build limit instead of stopping a room short of it.
			boolean last = y + height - 1 >= topY;
			int minY = last ? topY - height + 1 : y;

			if (drift > 0) {
				offsetX = clamp(offsetX + random.nextBetween(-drift, drift), maxDrift);
				offsetZ = clamp(offsetZ + random.nextBetween(-drift, drift), maxDrift);
			}

			int dx = columnX + offsetX - (box.getMinX() + box.getMaxX()) / 2;
			int dy = minY - box.getMinY();
			int dz = columnZ + offsetZ - (box.getMinZ() + box.getMaxZ()) / 2;
			for (StructurePiece piece : pieces) {
				piece.translate(dx, dy, dz);
				collector.addPiece(piece);
			}

			if (last) {
				return;
			}
			y = minY + height - overlap;
		}
	}

	/** One chamber with everything vanilla grows out of it, built at the scratch position. */
	private List<StructurePiece> generateRoom(Structure.Context context, BlockPos scratch) {
		Optional<Structure.StructurePosition> position = StructurePoolBasedGenerator.generate(
				context,
				startPool,
				Optional.empty(),
				size,
				scratch,
				false,
				Optional.empty(),
				maxDistanceFromCenter,
				// A different lookup position per room, so each room rolls its own mob set
				// instead of the whole tower sharing one.
				StructurePoolAliasLookup.create(poolAliasBindings,
						scratch.add(context.random().nextInt(4096), 0, context.random().nextInt(4096)), context.seed()),
				DimensionPadding.NONE,
				StructureLiquidSettings.IGNORE_WATERLOGGING
		);
		if (position.isEmpty()) {
			return List.of();
		}
		// Going through StructureStart is the one stable way to read the finished piece list.
		return new StructureStart(this, context.chunkPos(), 0, position.get().generate().toList()).getChildren();
	}

	private static int clamp(int value, int limit) {
		return Math.max(-limit, Math.min(limit, value));
	}

	@Override
	public StructureType<?> getType() {
		return TYPE;
	}
}
